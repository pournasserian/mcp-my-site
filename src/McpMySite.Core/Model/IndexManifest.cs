namespace McpMySite.Core.Model;

/// <summary>
/// Describes an index: which site it covers, how it was embedded and when it was built.
/// The server validates this before loading anything else.
/// </summary>
public sealed record IndexManifest
{
    public required int FormatVersion { get; init; }

    /// <summary>"json" or "sqlite".</summary>
    public required string StoreType { get; init; }

    public required string SiteUrl { get; init; }

    public string? SiteName { get; init; }

    public required string EmbeddingModel { get; init; }

    public required int EmbeddingDimensions { get; init; }

    public required DateTimeOffset BuiltAt { get; init; }

    public required int PageCount { get; init; }

    public required int ChunkCount { get; init; }

    /// <summary>Server instructions generated by the indexer (a short site outline).</summary>
    public string? Instructions { get; init; }

    public string? IndexerVersion { get; init; }

    public static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web)
    {
        WriteIndented = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    public string ToJson() => JsonSerializer.Serialize(this, JsonOptions);

    public static IndexManifest Parse(string json)
    {
        var manifest = JsonSerializer.Deserialize<IndexManifest>(json, JsonOptions)
            ?? throw new InvalidDataException("Manifest is empty.");
        manifest.Validate();
        return manifest;
    }

    /// <summary>Throws when the manifest cannot be served by this build.</summary>
    public void Validate()
    {
        if (!IndexFormat.IsSupported(FormatVersion))
        {
            throw new InvalidDataException(
                $"Index format version {FormatVersion} is not supported. Supported: {string.Join(", ", IndexFormat.SupportedVersions)}.");
        }

        if (StoreType is not (IndexFormat.JsonStoreType or IndexFormat.SqliteStoreType))
        {
            throw new InvalidDataException($"Unknown store type '{StoreType}'.");
        }

        if (string.IsNullOrWhiteSpace(SiteUrl))
        {
            throw new InvalidDataException("Manifest has no site URL.");
        }

        if (string.IsNullOrWhiteSpace(EmbeddingModel) || EmbeddingDimensions <= 0)
        {
            throw new InvalidDataException("Manifest has no embedding model or dimensions.");
        }

        if (PageCount <= 0)
        {
            throw new InvalidDataException("Manifest reports zero pages; refusing to load an empty index.");
        }
    }
}
