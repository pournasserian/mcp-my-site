namespace McpMySite.Server.Options;

public sealed class IndexOptions
{
    public const string SectionName = "Index";

    /// <summary>Local directory that holds the index files.</summary>
    public string? Path { get; set; }

    /// <summary>URL of the index: either the manifest.json or the directory that contains it.</summary>
    public string? Url { get; set; }

    /// <summary>How often to check for a new index. 0 disables polling.</summary>
    public int PollIntervalSeconds { get; set; } = 300;
}

public sealed class McpOptions
{
    public const string SectionName = "Mcp";

    public string Path { get; set; } = "/mcp";

    public string ServerName { get; set; } = "mcp-my-site";

    /// <summary>When set, requests must carry this key as a Bearer token or X-Api-Key header. Supply it via the Mcp__ApiKey environment variable.</summary>
    public string? ApiKey { get; set; }

    /// <summary>Replaces the instructions generated by the indexer.</summary>
    public string? Instructions { get; set; }

    /// <summary>Origins allowed to call the MCP endpoint from a browser. Empty disables CORS for it.</summary>
    public string[] AllowedOrigins { get; set; } = [];
}

public sealed class SearchApiOptions
{
    public const string SectionName = "SearchApi";

    public bool Enabled { get; set; } = true;

    public string Path { get; set; } = "/api/search";

    /// <summary>Origins allowed to call the search API from a browser (the site's own origin). Empty disables CORS for it.</summary>
    public string[] AllowedOrigins { get; set; } = [];

    public int DefaultLimit { get; set; } = 10;

    public int MaxLimit { get; set; } = 20;

    public int MaxQueryLength { get; set; } = 500;
}

public sealed class UiOptions
{
    public const string SectionName = "Ui";

    /// <summary>Serve the pages meant for people: the landing page and the API reference. The OpenAPI document is always served.</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// Public base URL of this server, such as https://mcp.example.com, used for canonical links, the sitemap and
    /// connection snippets. Empty takes it from each request.
    /// </summary>
    public string? PublicUrl { get; set; }

    /// <summary>The landing page flags the index as out of date when it is older than this. 0 never does.</summary>
    public int StaleAfterDays { get; set; } = 30;
}

public sealed class RateLimitOptions
{
    public const string SectionName = "RateLimiting";

    /// <summary>Requests allowed per client IP per minute across the MCP and search endpoints.</summary>
    public int PermitPerMinute { get; set; } = 60;

    /// <summary>Trust X-Forwarded-For from a reverse proxy such as Azure App Service when resolving the client IP.</summary>
    public bool UseForwardedHeaders { get; set; } = true;
}

public sealed class TelemetryOptions
{
    public const string SectionName = "Telemetry";

    /// <summary>Where traces, metrics and logs are exported on top of the console log.</summary>
    public TelemetryExporter Exporter { get; set; } = TelemetryExporter.Auto;

    /// <summary>
    /// Include the query text, and fetch targets that match no page, in logs and traces. Off by default because
    /// queries can contain personal data.
    /// </summary>
    public bool LogQueryText { get; set; }
}
