namespace McpMySite.Server.Options;

public sealed class IndexOptions
{
    public const string SectionName = "Index";

    /// <summary>Local directory that holds the index files.</summary>
    public string? Path { get; set; }

    /// <summary>URL of the index: either the manifest.json or the directory that contains it.</summary>
    public string? Url { get; set; }

    /// <summary>How often to check for a new index. 0 disables polling.</summary>
    public int PollIntervalSeconds { get; set; } = 300;
}

public sealed class McpOptions
{
    public const string SectionName = "Mcp";

    public string Path { get; set; } = "/mcp";

    public string ServerName { get; set; } = "mcp-my-site";

    /// <summary>When set, requests must carry this key as a Bearer token or X-Api-Key header. Supply it via the Mcp__ApiKey environment variable.</summary>
    public string? ApiKey { get; set; }

    /// <summary>Replaces the instructions generated by the indexer.</summary>
    public string? Instructions { get; set; }

    /// <summary>Origins allowed to call the MCP endpoint from a browser. Empty disables CORS for it.</summary>
    public string[] AllowedOrigins { get; set; } = [];
}

public sealed class SearchApiOptions
{
    public const string SectionName = "SearchApi";

    public bool Enabled { get; set; } = true;

    public string Path { get; set; } = "/api/search";

    /// <summary>Origins allowed to call the search API from a browser (the site's own origin). Empty disables CORS for it.</summary>
    public string[] AllowedOrigins { get; set; } = [];

    public int DefaultLimit { get; set; } = 10;

    public int MaxLimit { get; set; } = 20;

    public int MaxOffset { get; set; } = 100;

    public int MaxQueryLength { get; set; } = 500;
}

public sealed class UiOptions
{
    public const string SectionName = "Ui";

    /// <summary>Serve the pages meant for people: the landing page and the API reference. The OpenAPI document is always served.</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>Serve / as the landing page. Off, / is the short text summary and a browser on the MCP path is not redirected.</summary>
    public bool LandingPage { get; set; } = true;

    /// <summary>Serve the Scalar API reference at /docs. The OpenAPI document stays either way.</summary>
    public bool ApiReference { get; set; } = true;

    /// <summary>Mention the search API on the landing page and in /api/info. The endpoint itself follows SearchApi:Enabled.</summary>
    public bool ShowSearchApi { get; set; } = true;

    /// <summary>Show how search works: keyword-only or hybrid, embedding model and dimensions.</summary>
    public bool ShowSearchDetails { get; set; } = true;

    /// <summary>Show the last build: source, duration, page counts, embeddings, store and indexer version. Pages and build date stay.</summary>
    public bool ShowBuildDetails { get; set; } = true;

    public bool ServesLandingPage => Enabled && LandingPage;

    public bool ServesApiReference => Enabled && ApiReference;

    /// <summary>
    /// Public base URL of this server, such as https://mcp.example.com, used for canonical links, the sitemap and
    /// connection snippets. Empty takes it from each request.
    /// </summary>
    public string? PublicUrl { get; set; }

    /// <summary>The landing page flags the index as out of date when it is older than this. 0 never does.</summary>
    public int StaleAfterDays { get; set; } = 30;

    /// <summary>Origins allowed to embed the pages in a frame, as CSP frame-ancestors sources. Empty denies framing everywhere.</summary>
    public string[] FrameAncestors { get; set; } = [];
}

public sealed class RateLimitOptions
{
    public const string SectionName = "RateLimiting";

    /// <summary>Requests allowed per client IP per minute across the MCP and search endpoints.</summary>
    public int PermitPerMinute { get; set; } = 60;

    /// <summary>Trust X-Forwarded-For from a reverse proxy or platform ingress when resolving the client IP.</summary>
    public bool UseForwardedHeaders { get; set; } = true;
}

public sealed class TelemetryOptions
{
    public const string SectionName = "Telemetry";

    /// <summary>Where traces, metrics and logs are exported on top of the console log.</summary>
    public TelemetryExporter Exporter { get; set; } = TelemetryExporter.Auto;

    /// <summary>
    /// The metric groups to export, as a comma-separated list of <see cref="MetricGroups"/> names. Instruments of
    /// the other groups are dropped before export, whichever instrumentation or exporter registered them.
    /// </summary>
    public MetricGroups Metrics { get; set; } = MetricGroups.All;

    /// <summary>
    /// Include the query text, and fetch targets that match no page, in logs and traces. Off by default because
    /// queries can contain personal data.
    /// </summary>
    public bool LogQueryText { get; set; }

    /// <summary>
    /// Log the request and response bodies of the MCP endpoint and the search API, capped at 8 KB each, with an
    /// allowlist of headers and keys and secrets redacted. Includes the search text, so it is off by default.
    /// </summary>
    public bool LogBodies { get; set; }

    /// <summary>
    /// Tag each request, search and fetch with a visitor key: a hash of the client address and user agent with a
    /// random salt that is replaced every day and never stored. Counts distinct visitors without keeping addresses.
    /// </summary>
    public bool VisitorId { get; set; }
}

public sealed class CloudflareOptions
{
    public const string SectionName = "Cloudflare";

    /// <summary>
    /// Take the client IP from CF-Connecting-IP, and tag requests with CF-Ray and CF-IPCountry, when the
    /// connection comes from one of <see cref="TrustedNetworks"/>. Harmless without Cloudflare: a request from
    /// anywhere else keeps its own address.
    /// </summary>
    public bool TrustConnectingIp { get; set; } = true;

    /// <summary>
    /// CIDR ranges of the Cloudflare edge, from https://www.cloudflare.com/ips. Compared with the address of the
    /// caller after forwarded headers have been applied, so behind a reverse proxy it is the address the proxy saw.
    /// </summary>
    public string[] TrustedNetworks { get; set; } = [];
}
